const usedIds = new Set();

export function getRandomTask() {
  const unused = tasks.filter((t) => !usedIds.has(t.id));
  const pool = unused.length > 0 ? unused : tasks;
  if (unused.length === 0) usedIds.clear();
  const task = pool[Math.floor(Math.random() * pool.length)];
  usedIds.add(task.id);
  return task;
}
