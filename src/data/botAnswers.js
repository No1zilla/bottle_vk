export function getRandomBotAnswer(taskId) {
  const answers = BOT_ANSWERS_BY_TASK[taskId];
  if (!answers?.length) return 'Хм, это сложный вопрос...';
  return answers[Math.floor(Math.random() * answers.length)];
}
